"""SR CADLib: agent helper for building, placing and saving Fusion parts.

For AI agents driving Fusion (Fusion MCP ``execute_python`` or the script
runner). Humans are not expected to write scripts with it.

Call :func:`configure` first with the Fusion project name, folder root,
registry path and log path. There are no built-in project or machine paths.

Typical import from an agent-run Fusion script::

    import sys
    from pathlib import Path
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "sr-cadlib"))

    import sr_cadlib as cad
    cad.configure(
        project="MyProject",
        root="Products/Widget",
        registry_path="build/registry.json",
        log_path="build/build.log",
    )

Or install the package (``pip install -e .``) and import ``sr_cadlib`` without
changing ``sys.path``.
"""
